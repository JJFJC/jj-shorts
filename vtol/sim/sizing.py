"""First-order sizing of the tri-tiltrotor flying wing -> docs/SIZING.md

Textbook relations only (no CFD): trapezoid wing geometry, neutral point at the MAC quarter
chord, momentum theory for hover, parabolic drag polar for cruise, linear prop-thrust fall-off.
Every assumption is a named constant below; change params.py and re-run.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import params as P  # noqa: E402

G = 9.81
CD0 = 0.040  # flying wing + pod + 2 nacelles + stopped rear prop (assumed)
OSWALD = 0.80
FM = 0.55  # hover figure of merit, small prop
ETA_MOTOR = 0.80  # motor x ESC
ETA_PROP_CRUISE = 0.50  # small prop at part load; conservative
P_AVIONICS = 3.0  # W: flight controller, GPS, receiver, servos holding
V_CRUISE, V_FAST = 20.0, 28.0  # m/s
STATIC_MARGIN = 0.07  # of MAC, typical for a swept flying wing
LIPO_WH = 4 * 3.7 * 2.2  # 4S 2200 mAh
USABLE = 0.80
HOVER_S = 90.0  # takeoff + landing hover incl. transitions, seconds per flight
KV_RPM_PER_V, V_LOADED, PITCH_IN = 1700, 14.8 * 0.85, 4.5


def geometry():
    b_panel = P.HALF - P.POD_HALF_W
    lam = P.TIP_CHORD / P.ROOT_CHORD
    S = 2 * b_panel * (P.ROOT_CHORD + P.TIP_CHORD) / 2 + 2 * P.POD_HALF_W * P.ROOT_CHORD  # mm^2
    mac = 2 / 3 * P.ROOT_CHORD * (1 + lam + lam**2) / (1 + lam)
    y_mac = P.POD_HALF_W + (2 * b_panel) / 6 * (1 + 2 * lam) / (1 + lam)
    x_np = P.x_le(y_mac) + 0.25 * mac
    x_cg = x_np - STATIC_MARGIN * mac
    AR = P.SPAN**2 / S
    return dict(S_m2=S / 1e6, mac=mac, y_mac=y_mac, x_np=x_np, x_cg=x_cg, AR=AR)


def hover_power(T_N: float, prop_in: float) -> float:
    A = math.pi * (prop_in * 0.0254 / 2) ** 2
    return T_N**1.5 / math.sqrt(2 * P.AIR_DENSITY * A) / FM / ETA_MOTOR


def main():
    g = geometry()
    W_kg = sum(P.MASS.values()) / 1000
    W = W_kg * G
    # tricopter balance in hover: front pair at the pivot line, rear motor behind the CG
    x_f = P.x_le(P.FRONT_Y) - P.PIVOT_AHEAD_OF_LE
    a = g["x_cg"] - x_f
    x_r = g["x_cg"] + 2 * a  # rear at twice the distance -> all three motors share the load equally
    Tf_each = W * (2 * a) / (3 * a) / 2
    Tr = W - 2 * Tf_each
    T_max = 3 * P.MOTOR["max_thrust_g"] / 1000 * G
    p_hover = 2 * hover_power(Tf_each, P.PROP_D_FRONT_IN) + hover_power(Tr, P.PROP_D_REAR_IN)
    v_stall = math.sqrt(2 * W / (P.AIR_DENSITY * g["S_m2"] * P.CL_MAX))

    def drag(V):
        q = 0.5 * P.AIR_DENSITY * V * V
        CL = W / (q * g["S_m2"])
        return q * g["S_m2"] * (CD0 + CL * CL / (math.pi * OSWALD * g["AR"])), CL

    rows = []
    for V in range(12, 41, 2):
        D, CL = drag(V)
        P_el = D * V / ETA_PROP_CRUISE / ETA_MOTOR + P_AVIONICS
        rows.append((V, CL, D, P_el))
    e_wh = LIPO_WH * USABLE - p_hover * HOVER_S / 3600

    def p_at(V):
        D, _ = drag(V)
        return D * V / ETA_PROP_CRUISE / ETA_MOTOR + P_AVIONICS

    t_cruise_min = e_wh / p_at(V_CRUISE) * 60
    t_fast_min = e_wh / p_at(V_FAST) * 60
    # top speed: 2 front motors, thrust falls linearly to zero at the prop pitch speed
    v_pitch = KV_RPM_PER_V * V_LOADED * PITCH_IN * 0.0254 / 60
    T0 = 2 * P.MOTOR["max_thrust_g"] / 1000 * G
    v_max = 12.0
    for V in [x / 10 for x in range(120, 600)]:
        if T0 * (1 - V / v_pitch) >= drag(V)[0]:
            v_max = V

    lines = ["# VTOL tri-tiltrotor — first-order sizing", "", "Generated by `sim/sizing.py` from `params.py`. These are textbook estimates. Treat ±20% as normal; flight tests decide.", ""]
    lines += ["## Geometry", "", "| Item | Value |", "|---|---|"]
    lines += [f"| Span | {P.SPAN:.0f} mm |", f"| Wing area | {g['S_m2'] * 100:.1f} dm² (wing loading {W_kg / g['S_m2'] * 1000 / 100:.0f} g/dm²) |", f"| Aspect ratio | {g['AR']:.2f} |",
              f"| Mean aerodynamic chord | {g['mac']:.0f} mm at y = {g['y_mac']:.0f} mm |", f"| Leading-edge sweep / washout | {P.LE_SWEEP:.0f}° / {P.WASHOUT:.0f}° |",
              f"| Neutral point (x from root LE) | {g['x_np']:.0f} mm |", f"| **CG target** ({STATIC_MARGIN * 100:.0f}% static margin) | **{g['x_cg']:.0f} mm** behind the root LE |", ""]
    lines += ["## Weight", "", "| Item | g |", "|---|---|"] + [f"| {k} | {v} |" for k, v in P.MASS.items()] + [f"| **All-up weight** | **{W_kg * 1000:.0f}** |", ""]
    lines += ["## Hover (tri-tilt)", "", "| Item | Value |", "|---|---|",
              f"| Front tilt motors (pivot) | x = {x_f:.0f} mm, y = ±{P.FRONT_Y:.0f} mm |",
              f"| Rear lift motor | x = {x_r:.0f} mm (twice as far behind the CG as the front pair is ahead) |",
              f"| Hover thrust per motor | front {Tf_each / G * 1000:.0f} g each, rear {Tr / G * 1000:.0f} g |",
              f"| Max thrust / weight | {T_max / W:.1f} (3× {P.MOTOR['name']}, {P.MOTOR['max_thrust_g']:.0f} g each) |",
              f"| Hover power (all 3) | ≈ {p_hover:.0f} W ≈ {p_hover / 14.8:.0f} A at 4S |", ""]
    lines += ["## Forward flight (front motors tilted forward, rear motor stopped)", "", f"Stall ≈ **{v_stall:.1f} m/s ({v_stall * 3.6:.0f} km/h)**, so the transition must reach about {1.3 * v_stall * 3.6:.0f} km/h before the rotors finish tilting.", "",
              "| Speed m/s (km/h) | CL | Drag N | Electrical power W |", "|---|---|---|---|"]
    lines += [f"| {V} ({V * 3.6:.0f}) | {CL:.2f} | {D:.2f} | {Pe:.0f} |" for V, CL, D, Pe in rows]
    lines += ["", f"- **Cruise {V_CRUISE:.0f} m/s ({V_CRUISE * 3.6:.0f} km/h): ≈ {p_at(V_CRUISE):.0f} W → about {t_cruise_min:.0f} min** of flight after {HOVER_S:.0f} s of hover, on a 4S 2200 mAh pack used to {USABLE * 100:.0f}%.",
              f"- **Fast {V_FAST:.0f} m/s ({V_FAST * 3.6:.0f} km/h): ≈ {p_at(V_FAST):.0f} W → about {t_fast_min:.0f} min.**",
              f"- **Top speed ≈ {v_max:.0f} m/s ({v_max * 3.6:.0f} km/h)**, limited by thrust (prop pitch speed {v_pitch:.0f} m/s). A higher-pitch prop, e.g. 7×6, raises it but costs hover efficiency.", ""]
    lines += ["## Assumptions", "", f"CD0 = {CD0}, Oswald e = {OSWALD}, hover figure of merit = {FM}, motor×ESC η = {ETA_MOTOR}, prop η (cruise) = {ETA_PROP_CRUISE}, avionics {P_AVIONICS} W, CLmax = {P.CL_MAX}. Motor thrust is vendor-typical for 2207/1700 KV on 4S with a 7×4.5 prop; check it against the chart of the motor you buy.", ""]
    out = ROOT / "docs" / "SIZING.md"
    out.write_text("\n".join(lines) + "\n")
    import json

    (ROOT / "sim" / "sizing.json").write_text(json.dumps(dict(x_cg=g["x_cg"], x_np=g["x_np"], x_front=x_f, x_rear=x_r, auw_g=W_kg * 1000), indent=1))
    print(open(out).read())


if __name__ == "__main__":
    main()

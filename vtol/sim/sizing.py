"""First-order sizing of the tri-tiltrotor flying wing -> docs/SIZING.md

Textbook relations only (no CFD): trapezoid wing geometry, neutral point at the MAC quarter
chord, momentum theory for hover, parabolic drag polar for cruise, linear prop-thrust fall-off.
Every assumption is a named constant below; change params.py and re-run.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import params as P  # noqa: E402

G = 9.81
CD0 = 0.038  # blended body + canard + 4 nacelles (assumed)
OSWALD = 0.80
FM = 0.55  # hover figure of merit, small prop
ETA_MOTOR = 0.80  # motor x ESC
ETA_PROP_CRUISE = 0.50  # small prop at part load; conservative
P_AVIONICS = 3.0  # W: flight controller, GPS, receiver, servos holding
V_CRUISE, V_FAST = 20.0, 28.0  # m/s
STATIC_MARGIN = 0.12  # of main-wing MAC; canard aircraft want a healthy margin
LIPO_WH = 4 * 3.7 * 2.2  # 4S 2200 mAh
USABLE = 0.80
HOVER_S = 90.0  # takeoff + landing hover incl. transitions, seconds per flight
KV_RPM_PER_V, V_LOADED, PITCH_IN = 1700, 14.8 * 0.85, 4.5


def geometry():
    """Main blended wing (numerical over the section table) + canard; neutral point of the pair."""
    ys = [i * 2.0 for i in range(int(P.SPAN / 4) + 1)]
    S_w = ac_sum = mac_num = 0.0
    for y0, y1 in zip(ys, ys[1:]):
        c, xle, _ = P.chord_at(0.5 * (y0 + y1))
        dA = c * (y1 - y0)
        S_w += 2 * dA
        ac_sum += 2 * dA * (xle + 0.25 * c)
        mac_num += 2 * c * c * (y1 - y0)
    x_ac_w = ac_sum / S_w
    mac = mac_num / S_w
    C = P.CANARD
    S_c = C["span"] * C["chord"]
    x_ac_c = C["x_le"] + 0.25 * C["chord"]
    AR_w, AR_c = P.SPAN**2 / S_w, C["span"] ** 2 / S_c
    a_w = 2 * math.pi * AR_w / (2 + AR_w) * 0.85  # main wing sits in the canard's downwash
    a_c = 2 * math.pi * AR_c / (2 + AR_c)
    x_np = (a_c * S_c * x_ac_c + a_w * S_w * x_ac_w) / (a_c * S_c + a_w * S_w)
    x_cg = x_np - STATIC_MARGIN * mac
    S = S_w + S_c
    return dict(S_m2=S / 1e6, S_w=S_w / 1e6, S_c=S_c / 1e6, mac=mac, x_np=x_np, x_cg=x_cg, AR=P.SPAN**2 / S, x_ac_w=x_ac_w, x_ac_c=x_ac_c)


def hover_power(T_N: float, prop_in: float) -> float:
    A = math.pi * (prop_in * 0.0254 / 2) ** 2
    return T_N**1.5 / math.sqrt(2 * P.AIR_DENSITY * A) / FM / ETA_MOTOR


def main():
    g = geometry()
    W_kg = sum(P.MASS.values()) / 1000
    W = W_kg * G
    # quad balance in hover: front pair on the canard tips, rear pair on the main-wing nacelles
    x_f = P.FRONT_ROTOR["x_pivot"]
    c_r, xle_r, _ = P.chord_at(P.REAR_ROTOR["y"])
    x_r = xle_r + c_r + P.REAR_ROTOR["behind_te"]
    a, b = g["x_cg"] - x_f, x_r - g["x_cg"]
    Tf_each = W * b / (a + b) / 2
    Tr = W * a / (a + b) / 2  # per rear motor
    T_max = 4 * P.MOTOR["max_thrust_g"] / 1000 * G
    p_hover = 2 * hover_power(Tf_each, P.PROP_D_IN) + 2 * hover_power(Tr, P.PROP_D_IN)
    v_stall = math.sqrt(2 * W / (P.AIR_DENSITY * g["S_m2"] * P.CL_MAX))

    def drag(V):
        q = 0.5 * P.AIR_DENSITY * V * V
        CL = W / (q * g["S_m2"])
        return q * g["S_m2"] * (CD0 + CL * CL / (math.pi * OSWALD * g["AR"])), CL

    rows = []
    for V in range(12, 41, 2):
        D, CL = drag(V)
        P_el = D * V / ETA_PROP_CRUISE / ETA_MOTOR + P_AVIONICS
        rows.append((V, CL, D, P_el))
    e_wh = LIPO_WH * USABLE - p_hover * HOVER_S / 3600

    def p_at(V):
        D, _ = drag(V)
        return D * V / ETA_PROP_CRUISE / ETA_MOTOR + P_AVIONICS

    # efficient cruise: lowest power at or above 1.6x stall (keeps margin in gusts)
    V_eff = min((v / 2 for v in range(int(3.2 * v_stall), 70)), key=p_at)
    t_eff_min = e_wh / p_at(V_eff) * 60
    t_cruise_min = e_wh / p_at(V_CRUISE) * 60
    t_fast_min = e_wh / p_at(V_FAST) * 60
    # top speed: 2 front motors, thrust falls linearly to zero at the prop pitch speed
    v_pitch = KV_RPM_PER_V * V_LOADED * PITCH_IN * 0.0254 / 60
    T0 = 4 * P.MOTOR["max_thrust_g"] / 1000 * G  # all four rotors tilt forward
    v_max = 12.0
    for V in [x / 10 for x in range(120, 600)]:
        if T0 * (1 - V / v_pitch) >= drag(V)[0]:
            v_max = V

    lines = ["# KESTREL quad tilt-rotor VTOL — first-order sizing", "", "Generated by `sim/sizing.py` from `params.py`. These are textbook estimates. Treat ±20% as normal; flight tests decide.", ""]
    lines += ["## Geometry", "", "| Item | Value |", "|---|---|"]
    lines += [f"| Span | {P.SPAN:.0f} mm |", f"| Wing area | {g['S_m2'] * 100:.1f} dm² (wing loading {W_kg / g['S_m2'] * 1000 / 100:.0f} g/dm²) |", f"| Aspect ratio | {g['AR']:.2f} |",
              f"| Main wing (blended body) / canard area | {g['S_w'] * 100:.1f} / {g['S_c'] * 100:.1f} dm² |",
              f"| Main-wing MAC | {g['mac']:.0f} mm |", f"| Outer-wing LE sweep / washout | {P.LE_SWEEP:.0f}° / {P.WASHOUT:.0f}° |",
              f"| Neutral point (canard + wing) | x = {g['x_np']:.0f} mm |", f"| **CG target** ({STATIC_MARGIN * 100:.0f}% static margin) | **x = {g['x_cg']:.0f} mm** (x = 0 is the wing LE at the body/wing blend) |", ""]
    lines += ["## Weight", "", "| Item | g |", "|---|---|"] + [f"| {k} | {v} |" for k, v in P.MASS.items()] + [f"| **All-up weight** | **{W_kg * 1000:.0f}** |", ""]
    lines += ["## Hover (quad tilt-rotor)", "", "| Item | Value |", "|---|---|",
              f"| Front rotors (canard tips) | x = {x_f:.0f} mm, y = ±{P.FRONT_ROTOR['y']:.0f} mm |",
              f"| Rear rotors (trailing-edge pushers) | x = {x_r:.0f} mm, y = ±{P.REAR_ROTOR['y']:.0f} mm |",
              f"| Hover thrust per motor | front {Tf_each / G * 1000:.0f} g, rear {Tr / G * 1000:.0f} g (front share {Tf_each / (Tf_each + Tr) * 100:.0f}%) |",
              f"| Max thrust / weight | {T_max / W:.1f} (4× {P.MOTOR['name']}, {P.MOTOR['max_thrust_g']:.0f} g each) |",
              f"| Hover power (all 4) | ≈ {p_hover:.0f} W ≈ {p_hover / 14.8:.0f} A at 4S |", ""]
    lines += ["## Forward flight (all four rotors tilted forward)", "", f"Stall ≈ **{v_stall:.1f} m/s ({v_stall * 3.6:.0f} km/h)**, so the transition must reach about {1.3 * v_stall * 3.6:.0f} km/h before the rotors finish tilting.", "",
              "| Speed m/s (km/h) | CL | Drag N | Electrical power W |", "|---|---|---|---|"]
    lines += [f"| {V} ({V * 3.6:.0f}) | {CL:.2f} | {D:.2f} | {Pe:.0f} |" for V, CL, D, Pe in rows]
    lines += ["", f"- **Efficient cruise {V_eff:.1f} m/s ({V_eff * 3.6:.0f} km/h): ≈ {p_at(V_eff):.0f} W → about {t_eff_min:.0f} min.**",
              f"- **Cruise {V_CRUISE:.0f} m/s ({V_CRUISE * 3.6:.0f} km/h): ≈ {p_at(V_CRUISE):.0f} W → about {t_cruise_min:.0f} min** of flight.",
              f"- **Fast {V_FAST:.0f} m/s ({V_FAST * 3.6:.0f} km/h): ≈ {p_at(V_FAST):.0f} W → about {t_fast_min:.0f} min.**",
              f"- Flight times include {HOVER_S:.0f} s of hover and use a 4S 2200 mAh pack to {USABLE * 100:.0f}%. A 4S 3300 mAh pack (+90 g) adds about 45%.",
              f"- **Top speed ≈ {v_max:.0f} m/s ({v_max * 3.6:.0f} km/h)**, limited by thrust (prop pitch speed {v_pitch:.0f} m/s). A 7×6 prop or 5S raises it, at some cost in hover efficiency.", ""]
    lines += ["## Assumptions", "", f"CD0 = {CD0}, Oswald e = {OSWALD}, hover figure of merit = {FM}, motor×ESC η = {ETA_MOTOR}, prop η (cruise) = {ETA_PROP_CRUISE}, avionics {P_AVIONICS} W, CLmax = {P.CL_MAX}. Motor thrust is vendor-typical for 2207/1700 KV on 4S with a 7×4.5 prop; check it against the chart of the motor you buy.", ""]
    out = ROOT / "docs" / "SIZING.md"
    out.write_text("\n".join(lines) + "\n")
    import json

    (ROOT / "sim" / "sizing.json").write_text(json.dumps(dict(x_cg=g["x_cg"], x_np=g["x_np"], x_front=x_f, x_rear=x_r, auw_g=W_kg * 1000, front_share=Tf_each / (Tf_each + Tr)), indent=1))
    print(open(out).read())


if __name__ == "__main__":
    main()

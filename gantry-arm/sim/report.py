"""Turn sim/out/results.json into docs/SIM_REPORT.md.  Run after static_check.py."""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
import params as P  # noqa: E402

r = json.loads((HERE / "out" / "results.json").read_text())
S = r["structure"]
D = S["drives"]
FLAG = P.UTILISATION_FLAG

JOINTS = [
    ("base_yaw", "J1 base yaw"),
    ("shoulder_lift", "J2 shoulder"),
    ("elbow_flex", "J3 elbow"),
    ("wrist_flex", "J4 wrist pitch"),
    ("wrist_roll", "J5 wrist roll"),
]


def cap(j):
    s, n = P.JOINT_SERVOS[j]
    return s, n


def pct(x):
    return f"{x * 100:.0f}%"


lines = []
w = lines.append
w("# Gantry Arm — Step 1 simulation report")
w("")
w("Generated by `sim/static_check.py` + `sim/report.py` from `params.py`. Re-run both after changing any parameter.")
w("")
w("## Setup")
w("")
w(f"- Model: `urdf/gantry_arm.urdf` and `mjcf/gantry_arm.xml` (generated). 2 prismatic (X {P.X_TRAVEL:.0f} mm, Z {P.Z_TRAVEL:.0f} mm) + 5 revolute + gripper (2 mimic fingers).")
w(f"- Arm: J2→TCP reach **{r['reach_mm']:.0f} mm** (upper {P.ARM['upper']:.0f}, fore {P.ARM['fore']:.0f}, wrist {P.ARM['wrist']:.0f}, coupler {P.ARM['coupler']:.0f}, tool {P.ARM['tool_tcp']:.0f}).")
w(f"- Payload {P.MASS['payload']:.0f} g at the TCP, {P.MASS['payload_offset']:.0f} mm off the roll axis. Arm mass without payload {S['m_arm_kg'] - P.MASS['payload'] / 1000:.2f} kg.")
w("- **Masses come from the CAD**: every printed shell's volume × PETG density (`cad/out/mass_props.json`), plus a hardware allowance per body (`params.HARDWARE_G`) and the servos at their real positions. Re-run `cad/build_all.py` before the sim after any CAD change.")
w(f"- Elbow: **{P.ELBOW_SERVOS}× STS3250** (`params.ELBOW_SERVOS`, confirmed).")
w("- **Full reach** = shoulder 90° (arm horizontal), elbow 0, wrist 0, Z at top of travel. Static torques from MuJoCo `mj_inverse` (gravity + spring, zero velocity).")
w("- **Worst case** = max |torque| over a sweep of shoulder −100…100°, elbow −140…140°, wrist −110…110° (10° steps), with and without payload.")
w("- Servo ratings at 12 V: STS3215 stall 30 kg·cm (2.94 N·m), rated ~10 kg·cm; STS3250 stall 50 kg·cm (4.90 N·m), rated 16 kg·cm (1.57 N·m).")
w(f"- Shoulder spring: ideal zero-free-length spring (extension spring + cable over a pulley), anchor a = {P.SPRING['a']:.0f} mm above J2, attach b = {P.SPRING['b']:.0f} mm up the upper arm. "
  f"Stiffness swept 0–2 N/mm; **k = {r['k_opt']:.1f} N/mm** gives the lowest worst-case shoulder torque. Spring force {r['spring_Fh_N']:.0f} N with the arm horizontal, max {r['spring_Fmax_N']:.0f} N.")
w("- Assumed layout: the 2060 rail lies flat on the table, the 2040 column stands on the X carriage with its 40 mm faces toward ±Y, and the platform cantilevers +Y.")
w("")
w("## Joint torque at full reach (500 g)")
w("")
w(f"Flag rule: > {FLAG * 100:.0f}% of stall torque. The **% rated** column matters for holding a pose for a long time (heat).")
w("")
w("| Joint | Servo | No spring N·m | % stall | With spring N·m | % stall | % rated | Worst-case (spring) N·m | % stall | Flag |")
w("|---|---|---|---|---|---|---|---|---|---|")
for j, label in JOINTS:
    s, n = cap(j)
    st, ra = s.stall_Nm * n, s.rated_Nm * n
    a = abs(r["no_spring"]["full_reach"][j])
    b = abs(r["spring"]["full_reach"][j])
    wc = abs(r["spring"]["worst"][j][0])
    worst = max(b, wc) / st
    flag = "**FLAG**" if max(a if j != "shoulder_lift" else b, wc) / st > FLAG else ("**FLAG without spring**, ok with" if a / st > FLAG else "ok")
    name = f"{n}× {s.model.upper()}"
    note = ""
    if j == "base_yaw":
        note = " †"
    w(f"| {label}{note} | {name} | {a:.2f} | {pct(a / st)} | {b:.2f} | {pct(b / st)} | {pct(b / ra)} | {wc:.2f} | {pct(wc / st)} | {flag} |")
s15 = P.STS3215
w(f"| Gripper | 1× STS3215 | {r['gripper_T']:.3f} | {pct(r['gripper_T'] / s15.stall_Nm)} | — | — | {pct(r['gripper_T'] / s15.rated_Nm)} | — | — | ok |")
w("")
w("† J1 has a vertical axis, so gravity puts no torque on it. The number shown is the torque to accelerate the arm at 3 rad/s² at full reach. J1 must still carry a "
  f"**{S['j1_moment_Nm']:.1f} N·m bending moment**, and that has to go into a bearing, not the servo shaft.")
w(f"\nThe gripper needs {r['gripper_F']:.0f} N per finger (μ = {P.GRIPPER['mu_finger']}, safety factor {P.GRIPPER['safety']}) through a {P.GRIPPER['pinion_r']:.0f} mm pinion.")
w("")
sh_ns = abs(r["no_spring"]["full_reach"]["shoulder_lift"]) / (2 * P.STS3250.stall_Nm)
one = abs(r["no_spring"]["full_reach"]["shoulder_lift"]) / (2 * P.DUAL_SHARE) / P.STS3250.stall_Nm
w(f"Twin shoulder servos: with no spring and equal load sharing, J2 is at {pct(sh_ns)} of combined stall ({'over' if sh_ns > FLAG else 'under'} the 40% flag). "
  f"If the split is uneven (the worse servo carries 1/(2×{P.DUAL_SHARE}) = {1 / (2 * P.DUAL_SHARE):.0%} of the load), that servo is at {pct(one)} of its stall. "
  "The spring is what makes J2 safe.")
w("")
w("### Elbow fix options (what-if, spring on, full reach)")
w("")
w("| Option | J2 N·m | J3 N·m | J3 % stall | J3 % rated |")
w("|---|---|---|---|---|")
for label, j2, j3, fs, fr in r["elbow_options"]:
    w(f"| {label} | {j2:.2f} | {j3:.2f} | {pct(fs)} | {pct(fr)} |")
w("")
w("## Servo compliance (forward sim, holding the full-reach pose for 3 s)")
w("")
w("MuJoCo position actuators use the SO-101 measured STS3215 stiffness (kp = 17.8 N·m/rad, scaled by each servo's stall torque). That kp is the bus default P gain.")
w("")
w("| Case | J2 err ° | J3 err ° | J4 err ° | TCP drop mm |")
w("|---|---|---|---|---|")
for lab, key in (("Default P gain, no spring", ("no_spring", "sag")), ("Default P gain, spring", ("spring", "sag")), ("2× P gain (P_Coefficient 16→32), spring", ("spring", "sag_p2x")), ("Gravity feed-forward on goal, spring", ("spring", "sag_ff"))):
    e = r[key[0]][key[1]]
    w(f"| {lab} | {e['err_deg']['shoulder_lift']:.2f} | {e['err_deg']['elbow_flex']:.2f} | {e['err_deg']['wrist_flex']:.2f} | {e['tcp_drop_mm']:.1f} |")
w("")
w("Feed-forward means: add τ_gravity / kp to each goal position, using this same model. It is near-perfect in sim because the model is exact. "
  "On real hardware, expect a few mm, limited by mass errors and the servo deadband (±1 count = 0.09°).")
w("")
w("## Gantry structure (Z at top, arm at full reach, payload on)")
w("")
w(f"Hanging mass on the Z carriage: {S['m_hang_kg']:.2f} kg, CoM {S['com_y_mm']:.0f} mm in front of the column. Moment into the column: {S['M_col_Nm']:.1f} N·m at a height of {S['h_mm']:.0f} mm.")
w("")
w("| Contribution | TCP sag (mm) | Notes |")
w("|---|---|---|")
w(f"| 2040 column bending (strong axis) | {S['col_tcp_mm']:.2f} | rotation {S['col_rot_deg']:.3f}° |")
w(f"| Z carriage rocking on V-wheels | {S['zc_tcp_mm_hi']:.2f} – {S['zc_tcp_mm_lo']:.2f} | max wheel load {S['zc_wheel_load_N']:.0f} N (check against the wheel datasheet rating) |")
w(f"| X carriage rocking on 2060 | {S['xc_tcp_mm_hi']:.2f} – {S['xc_tcp_mm_lo']:.2f} | max wheel load {S['xc_wheel_load_N']:.0f} N |")
w(f"| PETG platform (ribbed, I = {S['plat_I_mm4'] / 1000:.0f}×10³ mm⁴) | {S['plat_tcp_mm']:.2f} | bending stress {S['plat_stress_MPa']:.1f} MPa (low, but PETG creeps under constant load) |")
w(f"| PETG arm links (hollow 3 mm wall) | {S['links_tcp_mm']:.2f} | conservative |")
tot_lo = S["col_tcp_mm"] + S["zc_tcp_mm_hi"] + S["xc_tcp_mm_hi"] + S["plat_tcp_mm"] + S["links_tcp_mm"]
tot_hi = S["col_tcp_mm"] + S["zc_tcp_mm_lo"] + S["xc_tcp_mm_lo"] + S["plat_tcp_mm"] + S["links_tcp_mm"]
w(f"| **Total elastic sag** | **{tot_lo:.1f} – {tot_hi:.1f}** | stiff vs. servo compliance |")
w("")
fl, fh = S["freq"]["lo"], S["freq"]["hi"]
w("**Wobble:** first natural frequency of the column with the platform and arm on it, Z at the top:")
w("")
w(f"- Along X (2040 weak axis + X carriage rocking): {fl['fx']:.1f} – {fh['fx']:.1f} Hz. A {P.X_ACCEL:.0f} mm/s² X move bends the column by {fh['x_accel_shift_mm']:.2f} – {fl['x_accel_shift_mm']:.2f} mm, and it rings at that frequency after the move.")
w(f"- Along Y (strong axis + X carriage rocking across the rail): {fl['fy']:.1f} – {fh['fy']:.1f} Hz.")
w("- Below ~15 Hz, it is visible in the wrist camera and couples with stepper mid-band resonance. The fix is cheap: an S-curve/jerk-limited X profile, a diagonal brace from the X carriage to the column, and preloaded (eccentric) wheels.")
w("")
w("## Drives")
w("")
w(f"- Z (T8×2): lift force {D['z_force_N']:.0f} N → {D['z_T_raise'] * 1000:.0f} mN·m to raise. The lowering torque is **+{D['z_T_lower'] * 1000:.1f} mN·m**, so the screw self-locks: lead angle {D['lead_angle']:.1f}° < friction angle {D['fric_angle']:.1f}° at μ = {P.Z_SCREW['mu_nut']}. "
  f"{P.Z_SPEED:.0f} mm/s needs {D['z_rpm']:.0f} rpm. A NEMA17 has plenty of torque there on 24 V, but only marginal on 12 V (torque falls off above ~500 rpm).")
w(f"- X (GT2 20T): {D['x_mass']:.1f} kg moving, {P.X_ACCEL:.0f} mm/s² + 8 N drag → {D['x_force']:.0f} N, {D['x_T'] * 1000:.0f} mN·m at {D['x_rpm']:.0f} rpm. Large margin.")
w("")
w("## Ranked weakest joints / parts")
w("")
e3 = r["elbow_options"][0]
j3_now = abs(r["spring"]["full_reach"]["elbow_flex"])
s50 = P.STS3250
n3 = P.ELBOW_SERVOS
sag = r["spring"]["sag"]["tcp_drop_mm"]
rows = [
    ("HIGH", "Servo position compliance", f"{sag:.0f} mm TCP drop at full reach with the default P gain (the spring already helps). This is 10× all the structural flex.", "Step 3: raise P_Coefficient on J2–J4 (lekiwi_pincopen heavy-joint pattern) **and** add gravity feed-forward to the goal positions."),
    (("HIGH" if n3 == 1 else "MED"), f"J3 elbow ({n3}× STS3250)",
     f"{pct(j3_now / (s50.stall_Nm * n3))} of stall, {pct(j3_now / (s50.rated_Nm * n3))} of rated (a single servo would be at {pct(e3[3])} / {pct(e3[4])})",
     "Twin ganged servos. Watch Present_Load on both servos for imbalance." if n3 == 2 else "Needs a design decision (see the elbow fix table)."),
    ("MED", "J2 shoulder without spring", f"{pct(sh_ns)} of combined stall; one servo goes over 40% if the two share load unevenly.", f"Keep the spring (k {r['k_opt']:.1f} N/mm): drops to {pct(abs(r['spring']['full_reach']['shoulder_lift']) / (2 * P.STS3250.stall_Nm))}. Monitor both servos' Present_Load."),
    ("MED", "J4 wrist pitch (STS3215)", f"{pct(abs(r['spring']['full_reach']['wrist_flex']) / s15.stall_Nm)} stall but {pct(abs(r['spring']['full_reach']['wrist_flex']) / s15.rated_Nm)} of rated", "OK for intermittent holds. Keep the tools light; the gripper tool is the heaviest."),
    ("MED", "J1 bending moment", f"{S['j1_moment_Nm']:.1f} N·m on the base", "Crossed-roller or lazy-susan bearing + a flex-free coupling to the STS3215 horn."),
    ("MED", "Gantry wobble", f"{min(fl['fx'], fl['fy']):.0f}–{max(fh['fx'], fh['fy']):.0f} Hz first mode", "Jerk-limited X moves, column brace, preloaded wheels."),
    ("MED", "Shoulder spring anchors", f"{r['spring_Fmax_N']:.0f} N max spring force", "Steel pin + bearing pulley; no plastic hook."),
    ("LOW", "Z carriage V-wheels", f"{S['zc_wheel_load_N']:.0f} N max per wheel", "Well inside typical V-wheel ratings (verify on datasheet); use double-row wheels as specified."),
    ("LOW", "Structure elastic sag", f"{tot_lo:.1f}–{tot_hi:.1f} mm", "Acceptable for pick/place, pen and phone tasks."),
    ("LOW", "J5 roll / gripper / X & Z drives", "< 5% of capacity", "—"),
]
w("| Rank | Severity | Item | Number | Mitigation |")
w("|---|---|---|---|---|")
for i, (sev, item, num, mit) in enumerate(rows, 1):
    w(f"| {i} | {sev} | {item} | {num} | {mit} |")
w("")
w("## Not modelled")
w("")
w("- URDF cannot express the shoulder spring; it is only in the MJCF (`tendon/shoulder_spring`).")
w("- Dynamic loads from arm motion are not in the static numbers (except the J1 example). Expect +20–50% during fast moves.")
w("- V-wheel stiffness is an estimate (300–1500 N/mm per wheel), so results are shown as a range.")
